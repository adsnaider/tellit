struct HighlightEngine {
    syntax_set: SyntaxSet,
    theme: Theme,
}

fn highlight_engine() -> &'static HighlightEngine {
    static ENGINE: OnceLock<HighlightEngine> = OnceLock::new();
    ENGINE.get_or_init(|| {
        let syntax_set = SyntaxSet::load_defaults_newlines();
        let mut theme_set = ThemeSet::load_defaults();
        let theme = theme_set
            .themes
            .remove("base16-ocean.dark")
            .or_else(|| theme_set.themes.into_values().next())
            .expect("syntect default ThemeSet contains at least one theme");
        HighlightEngine { syntax_set, theme }
    })
}

fn has_generated_infix_extension(file_name: &str, marker: &str) -> bool {
    let Some(idx) = file_name.rfind(marker) else {
        return false;
    };
    let ext = &file_name[idx + marker.len()..];
    !ext.is_empty() && ext.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

/// Checks whether `path` or its leading lines match known lockfile or codegen conventions.
#[must_use]
pub fn is_generated_file(path: &str, header_lines: &[&str]) -> bool {
    if path == COMMIT_MESSAGE_PATH {
        return false;
    }

    let file_name = path.rsplit('/').next().unwrap_or(path);
    if EXACT_GENERATED_FILENAMES.contains(&file_name) {
        return true;
    }
    if GENERATED_SUFFIXES.iter().any(|s| file_name.ends_with(s)) {
        return true;
    }
    if has_generated_infix_extension(file_name, ".generated.")
        || has_generated_infix_extension(file_name, ".gen.")
    {
        return true;
    }
    if (file_name.starts_with("mock_") || path.contains("mocks/")) && file_name.ends_with(".go") {
        return true;
    }
    if GENERATED_ROOT_PREFIXES.iter().any(|p| path.starts_with(p)) {
        return true;
    }
    if GENERATED_SEGMENTS.iter().any(|seg| path.contains(seg)) {
        return true;
    }

    // Documentation files frequently quote codegen markers as examples.
    let lower_name = file_name.to_ascii_lowercase();
    if lower_name.ends_with(".md") || lower_name.ends_with(".markdown") {
        return false;
    }

    for line in header_lines.iter().take(20) {
        let upper = line.to_ascii_uppercase();
        if line.contains("@generated")
            || upper.contains("DO NOT EDIT")
            || upper.contains("DO NOT MODIFY")
            || upper.contains("AUTO-GENERATED")
            || upper.contains("AUTOGENERATED")
            || upper.contains("THIS FILE IS GENERATED")
            || upper.contains("GENERATED CODE")
            || upper.contains("MACHINE GENERATED")
            || upper.contains("CODE GENERATED BY")
            || upper.contains("GENERATED BY ")
        {
            return true;
        }
    }

    false
}

fn decode_git_path(raw: &str, strip_git_prefix: bool) -> Option<String> {
    let trimmed = raw.trim();
    let before_tab = if trimmed.starts_with('"') {
        trimmed
    } else {
        trimmed.split('\t').next().unwrap_or(trimmed).trim()
    };
    let unquoted =
        if before_tab.starts_with('"') && before_tab.ends_with('"') && before_tab.len() >= 2 {
            &before_tab[1..before_tab.len() - 1]
        } else {
            before_tab
        };

    if unquoted == "/dev/null" {
        return None;
    }

    let mut stripped = unquoted;
    if strip_git_prefix {
        for prefix in ["a/", "b/", "c/", "i/", "w/"] {
            if let Some(rest) = stripped.strip_prefix(prefix) {
                stripped = rest;
                break;
            }
        }
    }

    if stripped == "/dev/null" {
        return None;
    }

    let mut bytes = Vec::with_capacity(stripped.len());
    let src = stripped.as_bytes();
    let mut i = 0;
    while i < src.len() {
        if src[i] == b'\\' && i + 1 < src.len() {
            let next = src[i + 1];
            if (b'0'..=b'7').contains(&next) {
                let mut val = u32::from(next - b'0');
                let mut consumed = 1usize;
                while consumed < 3 && i + 1 + consumed < src.len() {
                    let digit = src[i + 1 + consumed];
                    if !(b'0'..=b'7').contains(&digit) {
                        break;
                    }
                    val = (val << 3) + u32::from(digit - b'0');
                    consumed += 1;
                }
                if let Ok(byte) = u8::try_from(val) {
                    bytes.push(byte);
                }
                i += 1 + consumed;
                continue;
            }
            let escaped = match next {
                b't' => b'\t',
                b'n' => b'\n',
                b'r' => b'\r',
                b'\\' => b'\\',
                b'"' => b'"',
                b' ' => b' ',
                other => other,
            };
            bytes.push(escaped);
            i += 2;
            continue;
        }
        bytes.push(src[i]);
        i += 1;
    }

    Some(String::from_utf8_lossy(&bytes).into_owned())
}

struct HeaderPaths {
    old_path: Option<String>,
    new_path: Option<String>,
}

fn parse_diff_git_header(header_line: &str) -> Option<HeaderPaths> {
    let raw = header_line.strip_prefix("diff --git ")?;
    let mut parts = Vec::new();
    let mut current = String::new();
    let mut in_quotes = false;
    let mut escaped = false;

    for ch in raw.chars() {
        if escaped {
            current.push(ch);
            escaped = false;
            continue;
        }
        if ch == '\\' {
            current.push(ch);
            escaped = true;
            continue;
        }
        if ch == '"' {
            in_quotes = !in_quotes;
            current.push(ch);
            continue;
        }
        if ch == ' ' && !in_quotes {
            if !current.is_empty() {
                parts.push(core::mem::take(&mut current));
            }
            continue;
        }
        current.push(ch);
    }
    if !current.is_empty() {
        parts.push(current);
    }

    if parts.len() != 2 {
        return None;
    }

    Some(HeaderPaths {
        old_path: decode_git_path(&parts[0], true),
        new_path: decode_git_path(&parts[1], true),
    })
}

struct HunkRange {
    start: u32,
    count: u32,
}

struct HunkHeader {
    old_start: u32,
    old_lines: u32,
    new_start: u32,
    new_lines: u32,
}

fn parse_hunk_range(spec: &str) -> Option<HunkRange> {
    let trimmed = spec.trim_start_matches(['-', '+']);
    if let Some((start_s, count_s)) = trimmed.split_once(',') {
        Some(HunkRange {
            start: start_s.parse().ok()?,
            count: count_s.parse().ok()?,
        })
    } else {
        Some(HunkRange {
            start: trimmed.parse().ok()?,
            count: 1,
        })
    }
}

fn parse_hunk_header(line: &str) -> Option<HunkHeader> {
    let after_open = line.strip_prefix("@@ ")?;
    let (ranges_part, _) = after_open.split_once(" @@")?;
    let (old_spec, new_spec) = ranges_part.split_once(' ')?;
    let old = parse_hunk_range(old_spec)?;
    let new = parse_hunk_range(new_spec)?;
    Some(HunkHeader {
        old_start: old.start,
        old_lines: old.count,
        new_start: new.start,
        new_lines: new.count,
    })
}

fn parse_chunks(lines: &[&str]) -> Vec<DiffChunk> {
    let mut chunks = Vec::new();
    let mut current: Option<DiffChunk> = None;
    let mut old_line = 0u32;
    let mut new_line = 0u32;

    for &line in lines {
        if line.starts_with("@@ ") {
            if let Some(finished) = current.take() {
                chunks.push(finished);
            }
            if let Some(hdr) = parse_hunk_header(line) {
                old_line = hdr.old_start;
                new_line = hdr.new_start;
                current = Some(DiffChunk {
                    header: String::from(line),
                    old_start: hdr.old_start,
                    old_lines: hdr.old_lines,
                    new_start: hdr.new_start,
                    new_lines: hdr.new_lines,
                    lines: Vec::new(),
                });
            }
            continue;
        }

        let Some(ref mut chunk) = current else {
            continue;
        };

        if let Some(rest) = line.strip_prefix('+') {
            chunk.lines.push(DiffLine {
                kind: DiffLineKind::Add,
                content: String::from(rest),
                old_line_number: None,
                new_line_number: Some(new_line),
                syntax_spans: Vec::new(),
                word_diff: Vec::new(),
            });
            new_line += 1;
        } else if let Some(rest) = line.strip_prefix('-') {
            chunk.lines.push(DiffLine {
                kind: DiffLineKind::Delete,
                content: String::from(rest),
                old_line_number: Some(old_line),
                new_line_number: None,
                syntax_spans: Vec::new(),
                word_diff: Vec::new(),
            });
            old_line += 1;
        } else if let Some(rest) = line.strip_prefix(' ') {
            chunk.lines.push(DiffLine {
                kind: DiffLineKind::Context,
                content: String::from(rest),
                old_line_number: Some(old_line),
                new_line_number: Some(new_line),
                syntax_spans: Vec::new(),
                word_diff: Vec::new(),
            });
            old_line += 1;
            new_line += 1;
        }
    }

    if let Some(finished) = current {
        chunks.push(finished);
    }

    chunks
}

/// Base16 Ocean Dark non-default foreground RGB values matching CSS classes `.syn-1`..`.syn-19`.
const SYNTAX_PALETTE_RGB: [(u8, u8, u8); 19] = [
    (0x2b, 0x30, 0x3b), // 1:  base00
    (0x34, 0x3d, 0x46), // 2:  base01
    (0x4f, 0x5b, 0x66), // 3:  base02
    (0x65, 0x73, 0x7e), // 4:  base03 (comments)
    (0xa7, 0xad, 0xba), // 5:  base04
    (0xdf, 0xe1, 0xe8), // 6:  base06
    (0xef, 0xf1, 0xf5), // 7:  base07
    (0xbf, 0x61, 0x6a), // 8:  base08 (variables / tags)
    (0xd0, 0x87, 0x70), // 9:  base09 (numbers / constants)
    (0xeb, 0xcb, 0x8b), // 10: base0A (classes / types)
    (0xa3, 0xbe, 0x8c), // 11: base0B (strings)
    (0x96, 0xb5, 0xb4), // 12: base0C (escapes / support)
    (0x8f, 0xa1, 0xb3), // 13: base0D (functions)
    (0xb4, 0x8e, 0xad), // 14: base0E (keywords)
    (0xab, 0x79, 0x67), // 15: base0F (embedded / deprecated)
    (0x56, 0x56, 0x56), // 16: subtle delimiter/meta accent
    (0x96, 0x7e, 0xfb), // 17: purple accent
    (0xa6, 0xe2, 0x2e), // 18: green diff/inserted accent
    (0xf9, 0x26, 0x72), // 19: red diff/deleted accent
];

/// Minimum raw diff size before spawning worker threads for parallel file parsing.
const PARALLEL_DIFF_MIN_BYTES: usize = 8 * 1024;

/// Maps a `syntect` foreground [`Color`] to CSS palette index `0` (default) or `1..=19`.
fn color_to_palette_index(color: Color, default_fg: Option<Color>) -> u8 {
    if default_fg.is_some_and(|def| def.r == color.r && def.g == color.g && def.b == color.b) {
        return 0;
    }
    for (idx, &(r, g, b)) in SYNTAX_PALETTE_RGB.iter().enumerate() {
        if color.r == r && color.g == g && color.b == b {
            return u8::try_from(idx + 1).unwrap_or(0);
        }
    }
    // Nearest-RGB fallback if a theme ever produces a color outside the Base16 Ocean table.
    let mut best_idx = 0usize;
    let mut best_dist = u32::MAX;
    for (idx, &(r, g, b)) in SYNTAX_PALETTE_RGB.iter().enumerate() {
        let dr = i32::from(color.r) - i32::from(r);
        let dg = i32::from(color.g) - i32::from(g);
        let db = i32::from(color.b) - i32::from(b);
        let dist = u32::try_from(dr * dr + dg * dg + db * db).unwrap_or(u32::MAX);
        if dist < best_dist {
            best_dist = dist;
            best_idx = idx;
        }
    }
    u8::try_from(best_idx + 1).unwrap_or(0)
}

struct LineHighlighter<'a> {
    highlighter: Highlighter<'a>,
    parse_state: ParseState,
    highlight_state: HighlightState,
}

impl<'a> LineHighlighter<'a> {
    fn new(syntax: &SyntaxReference, theme: &'a Theme) -> Self {
        let highlighter = Highlighter::new(theme);
        let highlight_state = HighlightState::new(&highlighter, ScopeStack::new());
        Self {
            highlighter,
            parse_state: ParseState::new(syntax),
            highlight_state,
        }
    }

    fn states_equal(&self, other: &Self) -> bool {
        self.parse_state == other.parse_state && self.highlight_state == other.highlight_state
    }

    fn sync_from(&mut self, other: &Self) {
        self.parse_state = other.parse_state.clone();
        self.highlight_state = other.highlight_state.clone();
    }

    fn advance_without_spans(
        &mut self,
        syntax_set: &SyntaxSet,
        content: &str,
        line_buf: &mut String,
    ) {
        if content.is_empty() || content.len() > MAX_HIGHLIGHT_LINE_BYTES {
            return;
        }
        line_buf.clear();
        line_buf.push_str(content);
        line_buf.push('\n');
        let Ok(ops) = self.parse_state.parse_line(line_buf, syntax_set) else {
            return;
        };
        for _ in HighlightIterator::new(
            &mut self.highlight_state,
            &ops[..],
            line_buf,
            &self.highlighter,
        ) {}
    }

    fn highlight_line(
        &mut self,
        syntax_set: &SyntaxSet,
        default_fg: Option<Color>,
        content: &str,
        line_buf: &mut String,
    ) -> Vec<SyntaxSpan> {
        if content.is_empty() || content.len() > MAX_HIGHLIGHT_LINE_BYTES {
            return Vec::new();
        }
        line_buf.clear();
        line_buf.push_str(content);
        line_buf.push('\n');
        let Ok(ops) = self.parse_state.parse_line(line_buf, syntax_set) else {
            return Vec::new();
        };

        let mut spans: Vec<SyntaxSpan> = Vec::new();
        let mut has_styled = false;
        for (style, raw_slice) in HighlightIterator::new(
            &mut self.highlight_state,
            &ops[..],
            line_buf,
            &self.highlighter,
        ) {
            let slice = raw_slice.strip_suffix('\n').unwrap_or(raw_slice);
            if slice.is_empty() {
                continue;
            }
            let Ok(span_len) = u32::try_from(slice.len()) else {
                continue;
            };
            let palette_idx = color_to_palette_index(style.foreground, default_fg);
            if palette_idx != 0 {
                has_styled = true;
            }
            if let Some(last) = spans.last_mut()
                && last.style == palette_idx
            {
                last.len = last.len.saturating_add(span_len);
                continue;
            }
            spans.push(SyntaxSpan {
                len: span_len,
                style: palette_idx,
            });
        }

        // Omit spans entirely when every token uses the default foreground color.
        if !has_styled {
            return Vec::new();
        }
        spans
    }
}

fn find_syntax<'a>(syntax_set: &'a SyntaxSet, path: &str) -> Option<&'a SyntaxReference> {
    if path == COMMIT_MESSAGE_PATH {
        return None;
    }
    let p = Path::new(path);
    if let Some(ext) = p.extension().and_then(|e| e.to_str())
        && let Some(syn) = syntax_set.find_syntax_by_extension(ext)
    {
        return Some(syn);
    }
    if let Some(name) = p.file_name().and_then(|n| n.to_str())
        && let Some(syn) = syntax_set.find_syntax_by_extension(name)
    {
        return Some(syn);
    }
    // Common modern extensions mapped onto bundled syntaxes.
    match p.extension().and_then(|e| e.to_str()) {
        Some("ts" | "tsx" | "mts" | "cts" | "jsx" | "mjs" | "cjs") => {
            syntax_set.find_syntax_by_extension("js")
        }
        Some("toml" | "ini" | "cfg") => syntax_set
            .find_syntax_by_extension("toml")
            .or_else(|| syntax_set.find_syntax_by_extension("yaml")),
        Some("nix") => syntax_set.find_syntax_by_extension("sh"),
        _ => None,
    }
}

struct WordDiffPair {
    old_segments: Vec<WordDiffSegment>,
    new_segments: Vec<WordDiffSegment>,
}

fn compute_pair_word_diff(old_text: &str, new_text: &str) -> Option<WordDiffPair> {
    if old_text == new_text
        || old_text.is_empty()
        || new_text.is_empty()
        || old_text.len() > MAX_HIGHLIGHT_LINE_BYTES
        || new_text.len() > MAX_HIGHLIGHT_LINE_BYTES
    {
        return None;
    }

    let diff = TextDiff::from_words(old_text, new_text);
    let mut has_shared_non_ws = false;
    let mut old_segments: Vec<WordDiffSegment> = Vec::new();
    let mut new_segments: Vec<WordDiffSegment> = Vec::new();

    let push_segment = |target: &mut Vec<WordDiffSegment>, text: &str, emphasized: bool| {
        if text.is_empty() {
            return;
        }
        let Ok(seg_len) = u32::try_from(text.len()) else {
            return;
        };
        if let Some(last) = target.last_mut()
            && last.emphasized == emphasized
        {
            last.len = last.len.saturating_add(seg_len);
        } else {
            target.push(WordDiffSegment {
                len: seg_len,
                emphasized,
            });
        }
    };

    for change in diff.iter_all_changes() {
        let val = change.value();
        match change.tag() {
            ChangeTag::Equal => {
                if val.chars().any(|c| !c.is_whitespace()) {
                    has_shared_non_ws = true;
                }
                push_segment(&mut old_segments, val, false);
                push_segment(&mut new_segments, val, false);
            }
            ChangeTag::Delete => {
                push_segment(&mut old_segments, val, true);
            }
            ChangeTag::Insert => {
                push_segment(&mut new_segments, val, true);
            }
        }
    }

    if !has_shared_non_ws {
        return None;
    }

    Some(WordDiffPair {
        old_segments,
        new_segments,
    })
}

fn annotate_word_diffs(chunks: &mut [DiffChunk]) {
    for chunk in chunks {
        let len = chunk.lines.len();
        let mut idx = 0usize;
        while idx < len {
            if chunk.lines[idx].kind != DiffLineKind::Delete {
                idx += 1;
                continue;
            }
            let del_start = idx;
            while idx < len && chunk.lines[idx].kind == DiffLineKind::Delete {
                idx += 1;
            }
            let del_end = idx;
            let add_start = idx;
            while idx < len && chunk.lines[idx].kind == DiffLineKind::Add {
                idx += 1;
            }
            let add_end = idx;

            let del_count = del_end - del_start;
            let add_count = add_end - add_start;
            if del_count > 0 && del_count == add_count {
                for offset in 0..del_count {
                    let pair = compute_pair_word_diff(
                        &chunk.lines[del_start + offset].content,
                        &chunk.lines[add_start + offset].content,
                    );
                    if let Some(pair) = pair {
                        chunk.lines[del_start + offset].word_diff = pair.old_segments;
                        chunk.lines[add_start + offset].word_diff = pair.new_segments;
                    }
                }
            }
        }
    }
}

fn enrich_file_chunks(path: &str, chunks: &mut [DiffChunk]) {
    annotate_word_diffs(chunks);

    let engine = highlight_engine();
    let Some(syntax) = find_syntax(&engine.syntax_set, path) else {
        return;
    };
    let default_fg = engine.theme.settings.foreground;
    let mut line_buf = String::with_capacity(256);

    for chunk in chunks {
        let mut old_hl = LineHighlighter::new(syntax, &engine.theme);
        let mut new_hl = LineHighlighter::new(syntax, &engine.theme);
        for line in &mut chunk.lines {
            line.syntax_spans = match line.kind {
                DiffLineKind::Delete => old_hl.highlight_line(
                    &engine.syntax_set,
                    default_fg,
                    &line.content,
                    &mut line_buf,
                ),
                DiffLineKind::Add => new_hl.highlight_line(
                    &engine.syntax_set,
                    default_fg,
                    &line.content,
                    &mut line_buf,
                ),
                DiffLineKind::Context => {
                    if old_hl.states_equal(&new_hl) {
                        let spans = new_hl.highlight_line(
                            &engine.syntax_set,
                            default_fg,
                            &line.content,
                            &mut line_buf,
                        );
                        old_hl.sync_from(&new_hl);
                        spans
                    } else {
                        old_hl.advance_without_spans(
                            &engine.syntax_set,
                            &line.content,
                            &mut line_buf,
                        );
                        new_hl.highlight_line(
                            &engine.syntax_set,
                            default_fg,
                            &line.content,
                            &mut line_buf,
                        )
                    }
                }
            };
        }
    }
}

struct BlockHeader {
    path: String,
    old_path: Option<String>,
    status: FileStatus,
    header_end: usize,
}

fn parse_block_header(lines: &[&str]) -> Option<BlockHeader> {
    let header_line = *lines.first()?;
    let header_paths = parse_diff_git_header(header_line);

    // Stop header scanning at the first hunk marker so large files are not scanned repeatedly.
    let header_end = lines
        .iter()
        .position(|l| l.starts_with("@@ "))
        .unwrap_or(lines.len());

    let mut minus_line: Option<&str> = None;
    let mut plus_line: Option<&str> = None;
    let mut rename_from: Option<String> = None;
    let mut rename_to: Option<String> = None;
    let mut has_new_mode = false;
    let mut has_del_mode = false;

    for &line in &lines[..header_end] {
        if minus_line.is_none() && line.starts_with("--- ") {
            minus_line = Some(line);
        } else if plus_line.is_none() && line.starts_with("+++ ") {
            plus_line = Some(line);
        } else if rename_from.is_none()
            && let Some(raw) = line.strip_prefix("rename from ")
        {
            rename_from = decode_git_path(raw, false);
        } else if rename_to.is_none()
            && let Some(raw) = line.strip_prefix("rename to ")
        {
            rename_to = decode_git_path(raw, false);
        } else if line.starts_with("new file mode") {
            has_new_mode = true;
        } else if line.starts_with("deleted file mode") {
            has_del_mode = true;
        }
    }

    let minus_path = minus_line
        .and_then(|l| l.strip_prefix("--- "))
        .and_then(|raw| decode_git_path(raw, true));
    let plus_path = plus_line
        .and_then(|l| l.strip_prefix("+++ "))
        .and_then(|raw| decode_git_path(raw, true));

    let parsed_new = rename_to
        .or(plus_path)
        .or_else(|| header_paths.as_ref().and_then(|h| h.new_path.clone()));
    let parsed_old = rename_from
        .or(minus_path)
        .or_else(|| header_paths.as_ref().and_then(|h| h.old_path.clone()));

    let path = parsed_new.clone().or_else(|| parsed_old.clone())?;
    let old_candidate = parsed_old.unwrap_or_else(|| path.clone());

    let status = if has_new_mode || minus_line.is_some_and(|l| l.contains("/dev/null")) {
        FileStatus::Added
    } else if has_del_mode || plus_line.is_some_and(|l| l.contains("/dev/null")) {
        FileStatus::Deleted
    } else if old_candidate != path {
        FileStatus::Renamed
    } else {
        FileStatus::Modified
    };

    let old_path = if status == FileStatus::Renamed && old_candidate != path {
        Some(old_candidate)
    } else {
        None
    };

    Some(BlockHeader {
        path,
        old_path,
        status,
        header_end,
    })
}

fn parse_file_block(block: &str) -> Option<tellit_types::DiffFile> {
    let lines: Vec<&str> = block.lines().collect();
    let header = parse_block_header(&lines)?;

    let mut chunks = parse_chunks(&lines[header.header_end..]);
    let mut additions = 0u32;
    let mut deletions = 0u32;
    let mut header_sample: Vec<&str> = Vec::new();

    for chunk in &chunks {
        for line in &chunk.lines {
            match line.kind {
                DiffLineKind::Add => {
                    additions += 1;
                    if chunk.new_start == 1 && header_sample.len() < 20 {
                        header_sample.push(line.content.as_str());
                    }
                }
                DiffLineKind::Delete => {
                    deletions += 1;
                }
                DiffLineKind::Context => {
                    if chunk.new_start == 1 && header_sample.len() < 20 {
                        header_sample.push(line.content.as_str());
                    }
                }
            }
        }
    }

    let is_generated = is_generated_file(&header.path, &header_sample);
    if !is_generated {
        enrich_file_chunks(&header.path, &mut chunks);
    }

    Some(tellit_types::DiffFile {
        path: header.path,
        old_path: header.old_path,
        status: header.status,
        additions,
        deletions,
        is_generated,
        chunks,
        chunks_loaded: true,
    })
}

/// Parses and highlights a single `diff --git ...` file block into a [`tellit_types::DiffFile`].
#[must_use]
pub fn parse_single_file_block(block: &str) -> Option<tellit_types::DiffFile> {
    parse_file_block(block)
}

/// Fast header + line-count summary of a raw `git diff` / `jj diff --git` output without
/// running syntax highlighting or word-level diffing.
#[derive(Debug, Clone)]
pub struct DiffSummary {
    /// Summary-only [`tellit_types::DiffFile`] entries (`chunks: []`, `chunks_loaded: false`).
    pub files: Vec<tellit_types::DiffFile>,
    /// Byte ranges inside the raw diff text for O(1) single-file slice extraction by path.
    pub block_ranges: HashMap<String, Range<usize>>,
    /// Total number of hunk lines (`+`, `-`, and context) across all files.
    pub total_diff_lines: usize,
}

fn summarize_file_block(block: &str) -> Option<(tellit_types::DiffFile, usize)> {
    let lines: Vec<&str> = block.lines().collect();
    let header = parse_block_header(&lines)?;

    let mut additions = 0u32;
    let mut deletions = 0u32;
    let mut hunk_lines = 0usize;
    let mut in_hunk = false;
    let mut collect_header_sample = false;
    let mut header_sample: Vec<&str> = Vec::new();

    for &line in &lines[header.header_end..] {
        if line.starts_with("@@ ") {
            if let Some(hdr) = parse_hunk_header(line) {
                in_hunk = true;
                collect_header_sample = hdr.new_start == 1;
            } else {
                in_hunk = false;
                collect_header_sample = false;
            }
            continue;
        }
        if !in_hunk {
            continue;
        }

        if let Some(rest) = line.strip_prefix('+') {
            additions = additions.saturating_add(1);
            hunk_lines += 1;
            if collect_header_sample && header_sample.len() < 20 {
                header_sample.push(rest);
            }
        } else if line.starts_with('-') {
            deletions = deletions.saturating_add(1);
            hunk_lines += 1;
        } else if let Some(rest) = line.strip_prefix(' ') {
            hunk_lines += 1;
            if collect_header_sample && header_sample.len() < 20 {
                header_sample.push(rest);
            }
        }
    }

    let is_generated = is_generated_file(&header.path, &header_sample);
    Some((
        tellit_types::DiffFile {
            path: header.path,
            old_path: header.old_path,
            status: header.status,
            additions,
            deletions,
            is_generated,
            chunks: Vec::new(),
            chunks_loaded: false,
        },
        hunk_lines,
    ))
}

fn split_diff_block_ranges(diff_text: &str) -> Vec<Range<usize>> {
    let mut ranges = Vec::new();
    let mut current_start: Option<usize> = None;
    let mut line_offset = 0usize;

    for raw_line in diff_text.split_inclusive('\n') {
        if raw_line.starts_with("diff --git ") {
            if let Some(start) = current_start {
                ranges.push(start..line_offset);
            }
            current_start = Some(line_offset);
        }
        line_offset += raw_line.len();
    }

    if current_start.is_none() && diff_text.starts_with("diff --git ") {
        current_start = Some(0);
    }
    if let Some(start) = current_start {
        ranges.push(start..diff_text.len());
    }

    ranges
}

fn split_diff_blocks(diff_text: &str) -> Vec<&str> {
    split_diff_block_ranges(diff_text)
        .into_iter()
        .map(|range| &diff_text[range])
        .collect()
}

/// Scans `diff_text` in a single fast pass to produce file summaries, total diff line count,
/// and per-file byte ranges without allocating hunks or running `syntect`/`similar`.
#[must_use]
pub fn summarize_unified_git_diff(diff_text: &str) -> DiffSummary {
    let ranges = split_diff_block_ranges(diff_text);
    let mut files = Vec::with_capacity(ranges.len());
    let mut block_ranges = HashMap::with_capacity(ranges.len());
    let mut total_diff_lines = 0usize;

    for range in ranges {
        let block = &diff_text[range.clone()];
        if let Some((file, hunk_lines)) = summarize_file_block(block) {
            total_diff_lines = total_diff_lines.saturating_add(hunk_lines);
            block_ranges.insert(file.path.clone(), range);
            files.push(file);
        }
    }

    DiffSummary {
        files,
        block_ranges,
        total_diff_lines,
    }
}

/// Finds the raw `diff --git ...` block inside `diff_text` matching `target_path`.
#[must_use]
pub fn extract_file_block_by_path<'a>(diff_text: &'a str, target_path: &str) -> Option<&'a str> {
    for block in split_diff_blocks(diff_text) {
        let header_lines: Vec<&str> = block
            .lines()
            .take_while(|l| !l.starts_with("@@ "))
            .collect();
        if let Some(header) = parse_block_header(&header_lines)
            && header.path == target_path
        {
            return Some(block);
        }
    }
    None
}

/// Parses `git diff` / `jj diff --git` output into structured [`tellit_types::DiffFile`] entries.
///
/// Large multi-file diffs are parsed and highlighted in parallel across available CPU cores while
/// preserving the original file order from `diff_text`.
#[must_use]
pub fn parse_unified_git_diff(diff_text: &str) -> Vec<tellit_types::DiffFile> {
    let blocks = split_diff_blocks(diff_text);
    if blocks.is_empty() {
        return Vec::new();
    }

    let worker_count = std::thread::available_parallelism()
        .map_or(1, usize::from)
        .min(blocks.len());
    if worker_count <= 1 || diff_text.len() < PARALLEL_DIFF_MIN_BYTES {
        return blocks.into_iter().filter_map(parse_file_block).collect();
    }

    // Initialize the syntax/theme `OnceLock` once before fanning out to workers.
    let _ = highlight_engine();

    let next_idx = AtomicUsize::new(0);
    let block_count = blocks.len();
    let worker_outputs: Vec<Vec<(usize, Option<tellit_types::DiffFile>)>> =
        std::thread::scope(|scope| {
            let handles: Vec<_> = (0..worker_count)
                .map(|_| {
                    let blocks_ref = &blocks;
                    let next_ref = &next_idx;
                    scope.spawn(move || {
                        let mut local = Vec::new();
                        loop {
                            let idx = next_ref.fetch_add(1, Ordering::Relaxed);
                            if idx >= block_count {
                                break;
                            }
                            local.push((idx, parse_file_block(blocks_ref[idx])));
                        }
                        local
                    })
                })
                .collect();

            handles
                .into_iter()
                .map(|handle| handle.join().unwrap_or_default())
                .collect()
        });

    let mut ordered: Vec<Option<tellit_types::DiffFile>> = (0..block_count).map(|_| None).collect();
    for batch in worker_outputs {
        for (idx, file) in batch {
            ordered[idx] = file;
        }
    }
    ordered.into_iter().flatten().collect()
}

/// Builds the virtual `"Commit Message"` [`tellit_types::DiffFile`] comparing descriptions.
#[must_use]
pub fn build_commit_message_file(
    base_desc: &str,
    target_desc: &str,
    is_inter_diff: bool,
) -> tellit_types::DiffFile {
    let norm_base = base_desc.replace("\r\n", "\n").trim_end().to_owned();
    let norm_target = target_desc.replace("\r\n", "\n").trim_end().to_owned();

    if !is_inter_diff {
        if norm_target.is_empty() {
            return tellit_types::DiffFile {
                path: String::from(COMMIT_MESSAGE_PATH),
                old_path: None,
                status: FileStatus::Modified,
                additions: 0,
                deletions: 0,
                is_generated: false,
                chunks: alloc::vec![DiffChunk {
                    header: String::from("@@ -1,1 +1,1 @@"),
                    old_start: 1,
                    old_lines: 1,
                    new_start: 1,
                    new_lines: 1,
                    lines: alloc::vec![DiffLine {
                        kind: DiffLineKind::Context,
                        content: String::from("(no description set)"),
                        old_line_number: Some(1),
                        new_line_number: Some(1),
                        syntax_spans: Vec::new(),
                        word_diff: Vec::new(),
                    }],
                }],
                chunks_loaded: true,
            };
        }

        let target_lines: Vec<&str> = norm_target.split('\n').collect();
        let count = u32::try_from(target_lines.len()).unwrap_or(u32::MAX);
        let lines = target_lines
            .into_iter()
            .enumerate()
            .map(|(idx, text)| DiffLine {
                kind: DiffLineKind::Add,
                content: String::from(text),
                old_line_number: None,
                new_line_number: Some(u32::try_from(idx + 1).unwrap_or(u32::MAX)),
                syntax_spans: Vec::new(),
                word_diff: Vec::new(),
            })
            .collect();

        return tellit_types::DiffFile {
            path: String::from(COMMIT_MESSAGE_PATH),
            old_path: None,
            status: FileStatus::Added,
            additions: count,
            deletions: 0,
            is_generated: false,
            chunks: alloc::vec![DiffChunk {
                header: alloc::format!("@@ -0,0 +1,{count} @@"),
                old_start: 0,
                old_lines: 0,
                new_start: 1,
                new_lines: count,
                lines,
            }],
            chunks_loaded: true,
        };
    }

    if norm_base == norm_target {
        let display = if norm_target.is_empty() {
            "(no description set)"
        } else {
            norm_target.as_str()
        };
        let display_lines: Vec<&str> = display.split('\n').collect();
        let count = u32::try_from(display_lines.len()).unwrap_or(u32::MAX);
        let lines = display_lines
            .into_iter()
            .enumerate()
            .map(|(idx, text)| {
                let n = u32::try_from(idx + 1).unwrap_or(u32::MAX);
                DiffLine {
                    kind: DiffLineKind::Context,
                    content: String::from(text),
                    old_line_number: Some(n),
                    new_line_number: Some(n),
                    syntax_spans: Vec::new(),
                    word_diff: Vec::new(),
                }
            })
            .collect();

        return tellit_types::DiffFile {
            path: String::from(COMMIT_MESSAGE_PATH),
            old_path: None,
            status: FileStatus::Modified,
            additions: 0,
            deletions: 0,
            is_generated: false,
            chunks: alloc::vec![DiffChunk {
                header: alloc::format!("@@ -1,{count} +1,{count} @@"),
                old_start: 1,
                old_lines: count,
                new_start: 1,
                new_lines: count,
                lines,
            }],
            chunks_loaded: true,
        };
    }

    let old_with_nl = if norm_base.is_empty() {
        String::new()
    } else {
        alloc::format!("{norm_base}\n")
    };
    let new_with_nl = if norm_target.is_empty() {
        String::new()
    } else {
        alloc::format!("{norm_target}\n")
    };

    let text_diff = TextDiff::from_lines(&old_with_nl, &new_with_nl);
    let mut chunks = Vec::new();
    let mut additions = 0u32;
    let mut deletions = 0u32;

    for group in text_diff.grouped_ops(3) {
        let Some(first) = group.first() else {
            continue;
        };
        let Some(last) = group.last() else {
            continue;
        };

        let old_range_start = first.old_range().start;
        let old_range_end = last.old_range().end;
        let new_range_start = first.new_range().start;
        let new_range_end = last.new_range().end;

        let old_lines = u32::try_from(old_range_end - old_range_start).unwrap_or(0);
        let new_lines = u32::try_from(new_range_end - new_range_start).unwrap_or(0);
        let old_start = if old_lines == 0 {
            0
        } else {
            u32::try_from(old_range_start + 1).unwrap_or(1)
        };
        let new_start = if new_lines == 0 {
            0
        } else {
            u32::try_from(new_range_start + 1).unwrap_or(1)
        };

        let mut lines = Vec::new();
        for op in &group {
            for change in text_diff.iter_changes(op) {
                let text = change.value().trim_end_matches(['\r', '\n']);
                match change.tag() {
                    ChangeTag::Equal => {
                        lines.push(DiffLine {
                            kind: DiffLineKind::Context,
                            content: String::from(text),
                            old_line_number: change
                                .old_index()
                                .and_then(|i| u32::try_from(i + 1).ok()),
                            new_line_number: change
                                .new_index()
                                .and_then(|i| u32::try_from(i + 1).ok()),
                            syntax_spans: Vec::new(),
                            word_diff: Vec::new(),
                        });
                    }
                    ChangeTag::Delete => {
                        deletions += 1;
                        lines.push(DiffLine {
                            kind: DiffLineKind::Delete,
                            content: String::from(text),
                            old_line_number: change
                                .old_index()
                                .and_then(|i| u32::try_from(i + 1).ok()),
                            new_line_number: None,
                            syntax_spans: Vec::new(),
                            word_diff: Vec::new(),
                        });
                    }
                    ChangeTag::Insert => {
                        additions += 1;
                        lines.push(DiffLine {
                            kind: DiffLineKind::Add,
                            content: String::from(text),
                            old_line_number: None,
                            new_line_number: change
                                .new_index()
                                .and_then(|i| u32::try_from(i + 1).ok()),
                            syntax_spans: Vec::new(),
                            word_diff: Vec::new(),
                        });
                    }
                }
            }
        }

        chunks.push(DiffChunk {
            header: alloc::format!("@@ -{old_start},{old_lines} +{new_start},{new_lines} @@"),
            old_start,
            old_lines,
            new_start,
            new_lines,
            lines,
        });
    }

    annotate_word_diffs(&mut chunks);

    tellit_types::DiffFile {
        path: String::from(COMMIT_MESSAGE_PATH),
        old_path: None,
        status: FileStatus::Modified,
        additions,
        deletions,
        is_generated: false,
        chunks,
        chunks_loaded: true,
    }
}

